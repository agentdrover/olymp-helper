"""T-G3: a second model of the other channel solves a generated question without the key."""

import json

from app.model.types import ModelResult
from tests.bank_helpers import PARENT, db
from tests.test_generated_packs import NEW, PackModel, make_bank, request_pack


class CrossModel(PackModel):
    """Generation by claude; `second` answers on the other channel (None = channel down)."""

    def __init__(self, second, **kw):
        super().__init__(**kw)
        self.second = second
        self.cross_calls = []

    def complete_on(self, channel, system, messages, schema=None, session_id=None):
        self.cross_calls.append((channel, system, messages, schema))
        answer = self.second(messages[-1]["content"]) if callable(self.second) else self.second
        if answer is None:
            return ModelResult.failure(channel, "stub", "executor_unreachable")
        return ModelResult(None, answer, channel, "stub", 1, None)


def solve(answer, valid=True, **extra):
    return {
        "proposed_answer": answer,
        "explanation": "довод второй модели",
        "valid": valid,
        **extra,
    }


def run_pack(tmp_path, second, questions=None):
    def factory(tasks, pack):
        return CrossModel(second, bank=tasks, pack=pack)

    return make_bank(tmp_path, {"questions": questions or [NEW[0]]}, factory=factory)


def row(tmp_path, n=0):
    conn = db(tmp_path)
    try:
        return conn.execute("SELECT * FROM task_item WHERE key_source = 'generated'").fetchall()[n]
    finally:
        conn.close()


def stored(tmp_path, n=0):
    return json.loads(row(tmp_path, n)["crosscheck"])


def cards(c):
    return c.get("/parent/review/queue", headers=PARENT).json()["cards"]


def generated_card(c, tmp_path):
    return next(x for x in cards(c) if x["task_id"] == row(tmp_path)["id"])


def test_a_disagreeing_second_model_flags_the_question(tmp_path):
    c, model = run_pack(tmp_path, solve("А"))  # the key of NEW[0] is Г
    with c:
        request_pack(c, 1)
        (channel, system, messages, _) = model.cross_calls[0]
        assert channel == "cursor"  # generated by claude -> solved by the other channel
        sent = system + messages[0]["content"]
        assert "answer_key" not in sent and "потому что так" not in sent  # no key, no rationale
        assert "Какой органоид содержит хлорофилл" in sent

        record = stored(tmp_path)
        assert record["status"] == "disagrees" and record["answer"] == "А"
        assert record["reasoning"] == "довод второй модели" and record["channel"] == "cursor"

        card = generated_card(c, tmp_path)
        assert card["kind"] == "crosscheck" and card["crosscheck"]["reasoning"]
        tid = card["task_id"]

        # no confirmation without reading the reasoning, neither plain nor with own answer
        for body in ({}, {"answer": "Г"}):
            r = c.post(f"/parent/tasks/{tid}/confirm", headers=PARENT, json=body)
            assert r.status_code == 422, r.text
        assert row(tmp_path)["import_status"] == "draft"

        assert c.post(f"/parent/tasks/{tid}/crosscheck-seen", headers=PARENT).status_code == 200
        assert c.post(f"/parent/tasks/{tid}/confirm", headers=PARENT, json={}).status_code == 200
        assert row(tmp_path)["import_status"] == "checked"


def test_an_agreeing_second_model_marks_the_question(tmp_path):
    c, _ = run_pack(tmp_path, solve("Г"))
    with c:
        request_pack(c, 1)
        assert stored(tmp_path)["status"] == "agrees"
        card = generated_card(c, tmp_path)
        assert card["kind"] == "confirm" and card["crosscheck"]["label"] == "вторая модель согласна"
        r = c.post(f"/parent/tasks/{card['task_id']}/confirm", headers=PARENT, json={})
        assert r.status_code == 200


def test_a_question_judged_invalid_is_a_disagreement(tmp_path):
    c, _ = run_pack(tmp_path, solve("Г", valid=False, problem="два верных ответа"))
    with c:
        request_pack(c, 1)
        record = stored(tmp_path)
        assert record["status"] == "disagrees" and record["invalid"] is True
        assert "два верных ответа" in record["reasoning"]


def test_an_unavailable_second_channel_is_not_checked_but_confirmable(tmp_path):
    c, _ = run_pack(tmp_path, None)
    with c:
        request_pack(c, 1)
        assert stored(tmp_path)["status"] == "unchecked"
        card = generated_card(c, tmp_path)
        assert card["crosscheck"]["label"] == "не сверено" and card["crosscheck"]["warning"]
        r = c.post(f"/parent/tasks/{card['task_id']}/confirm", headers=PARENT, json={})
        assert r.status_code == 200


def test_disagreements_are_at_the_top_of_the_queue(tmp_path):
    # keys: NEW[0] = Г (agrees), NEW[1] = А (second model says Б: disagrees)
    c, _ = run_pack(
        tmp_path,
        lambda content: solve("Б" if "Где в клетке" in content else "Г"),
        questions=[NEW[0], NEW[1]],
    )
    with c:
        request_pack(c, 2)
        assert [stored(tmp_path, n)["status"] for n in range(2)] == ["agrees", "disagrees"]
        kinds = [x["kind"] for x in cards(c)]
        assert kinds[0] == "crosscheck" and kinds.count("crosscheck") == 1
